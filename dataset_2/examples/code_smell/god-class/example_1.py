"""Gerenciamento de pedidos: criacao, estoque, fiscal, notificacao e auditoria."""


class GerenciadorPedido:
    def __init__(self):
        self.pedidos = []

    def criar_pedido(self, dados):
        self.validar_estoque(dados["produto_id"], dados["quantidade"])
        imposto = self.calcular_imposto(dados["valor"], dados["estado"])
        frete = self.calcular_frete(dados["cep"], dados["peso"])
        pedido = {**dados, "imposto": imposto, "frete": frete}
        self.pedidos.append(pedido)
        self.enviar_email_confirmacao(dados["email"], pedido)
        self.gerar_nota_fiscal_pdf(pedido)
        self.registrar_log_auditoria(f"pedido criado: {dados}")
        return pedido

